export type Field =
  | "Robotics"
  | "Soft Matter Physics"
  | "Civil Engineering"
  | "Biology"
  | "Materials Science"
  | "Physics"
  | "Computer Science"
  | "Ecology"
  | "Medicine"
  | "Economics";

export type SerendipityLevel = "focused" | "balanced" | "exploratory";

export interface SerendipitySettings {
  level: SerendipityLevel;
  /** How many adjacent fields (beyond the home field) are excluded */
  excludedAdjacent: number;
  /** How far down the ranked candidate list the agent explores */
  rankDepth: number;
}

export interface CollisionInput {
  text: string;
  homeFields: Field[];
  serendipity: SerendipitySettings;
}

export interface Abstraction {
  functional_problem: string;
  constraints: string[];
  mechanism?: string;
  domain_tags?: string[];
}

export type ReviewStatus = "supported" | "plausible" | "contested";
export type Heresy = "low" | "medium" | "high";
export type MatchedOn = "problem" | "mechanism";

export interface Candidate {
  id: string;
  title: string;
  field: Field;
  tags: string[];
  /** Demonstration score 0-100 — NOT a measured value */
  mockScore: number;
  /** Not part of the frozen contract: only live/old demo candidates have it */
  reviewerConfidence?: number;
  explanation: string;
  hypothesis: string;
  /** Not part of the frozen contract: only live/old demo candidates have it */
  reviewStatus?: ReviewStatus;
  /** Contract result fields (hero fixture / real API) */
  heresy?: Heresy;
  matchedOn?: MatchedOn;
  paper?: { year?: number | string; venue?: string; doi?: string };
  /** Contract field: where the analogy breaks */
  reviewerNote?: string;
  fixture?: boolean;
  source: { citation: string; passage: string | null };
  mapping: { source: string; home: string }[];
  reviewer: {
    useful: string;
    similar: string[];
    assumptions: string[];
    failure: string[];
    next: string[];
  };
  image?: "ant";
  /** True when generated by the live model, not from the bundled fixtures */
  live?: boolean;
  /** The structural abstraction of the problem this live candidate answers */
  abstraction?: Abstraction;
  /** The problem text the user submitted for this live run */
  problem?: string;
}

export type TraceState = "waiting" | "running" | "completed" | "skipped" | "failed";
export interface TraceMeta {
  task?: string;
  cached?: boolean;
  attempt?: number;
  ms?: number;
}
export interface TraceEvent {
  id: string;
  step: string;
  meta?: TraceMeta;
  message: string;
  detail?: string;
  state: TraceState;
  elapsedMs?: number;
}

export interface Run {
  id: string;
  input: CollisionInput;
  status: "running" | "completed" | "failed";
  startedAt: number;
  trace: TraceEvent[];
  resultIds: string[];
  rejected: { id: string; reason: string; title?: string }[];
  cachedFallback: boolean;
  /** Set when the structural abstraction came back from Gemini */
  abstraction?: Abstraction;
  abstractionNote?: string;
  /** Live model candidates (replace the bundled fixtures when present) */
  candidates?: Candidate[];
  liveStage?: "pending" | "done" | "failed";
  /** True when this run replays the frozen hero fixture (src/mock/hero_run.json) */
  fixture?: boolean;
  /** Fixture only: milliseconds to wait before each trace event appears */
  delays?: number[];
  liveNote?: string;
}

export interface ValidationCase {
  id: string;
  name: string;
  researcherField: string;
  expectedSource: string;
  baseline: string;
  structural: string;
  topK: string;
  status: "Not Run" | "Awaiting Measured Data";
}
